/**
 * `aria-hidden` because a spinner is decoration: the surrounding control announces the state
 * (a submit button sets aria-busy, a loading region uses role="status"). Without it a screen
 * reader would read out a meaningless graphic.
 */
export function Spinner({ className = "size-4" }: { className?: string }) {
  return (
    <svg className={`animate-spin ${className}`} viewBox="0 0 24 24" fill="none" aria-hidden="true">
      <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4" />
      <path
        className="opacity-75"
        fill="currentColor"
        d="M4 12a8 8 0 018-8v4a4 4 0 00-4 4H4z"
      />
    </svg>
  );
}
