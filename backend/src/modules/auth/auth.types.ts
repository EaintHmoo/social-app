import type { User } from "../../generated/prisma/client.js";
import type { z } from "zod";
import type { loginSchema, refreshSchema, registerSchema } from "./auth.validator.js";

// Every type the auth module owns, in one file next to the code that uses it. Previously these
// were spread across src/types/{auth,models,resources,validators}.ts — one file per LAYER, which
// meant every auth type sat beside unrelated types from other features.
//
// Laravel: the `$fillable`/`$casts` shape of the Eloquent models, the array each API Resource's
// toArray() returns, and the shape of `$request->validated()` for each FormRequest.

// ─── Database rows ───────────────────────────────────────────────────────────
// The row shapes are generated by Prisma from prisma/schema.prisma (`npm run db:generate`), so
// they can never drift from the actual tables. Re-exported here so the rest of the module keeps
// importing its types from one place.

export type { Session, SessionRevokeReason } from "../../generated/prisma/client.js";

// A user as every normal query returns it: the password hash is omitted by default
// (see shared/config/prisma.ts), and this type says so, so it can't be read by accident.
// Keep the key in sync with the schema: Omit<> silently accepts a key that no longer exists.
export type SafeUser = Omit<User, "passwordHash">;

// ─── Tokens & sessions ───────────────────────────────────────────────────────

// Captured from the request at login and stored on the session — see auth.request.ts.
export interface DeviceInfo {
  userAgent: string | null;
  ip: string | null;
}

export interface TokenPair {
  accessToken: string;
  refreshToken: string;
}

// What register/login hand back to the controller.
export interface AuthResult {
  user: SafeUser;
  tokens: TokenPair;
}

// Claims we put into each JWT (iat/exp are added by jsonwebtoken) — see jwt.ts.
export interface AccessTokenPayload {
  sub: string;
  email: string;
  sid: string;
  iat: number;
  exp: number;
}

export interface RefreshTokenPayload {
  sub: string;
  sid: string;
  jti: string;
  iat: number;
  exp: number;
}

// ─── Resources (the JSON shape clients receive) ──────────────────────────────

export interface UserResource {
  id: string;
  username: string;
  display_name: string;
  email: string;
  email_verified: boolean;
}

export interface SessionResource {
  id: string;
  current: boolean;
  user_agent: string | null;
  ip: string | null;
  signed_in_at: Date;
  last_used_at: Date;
  expires_at: Date;
}

// ─── Validated request bodies ────────────────────────────────────────────────
// Inferred from the zod schemas in auth.validator.ts, so the rules and the types can never drift.

export type RegisterInput = z.infer<typeof registerSchema>;
export type LoginInput = z.infer<typeof loginSchema>;
export type RefreshInput = z.infer<typeof refreshSchema>;
